# ---- 出力 -------------------------------------------------------------------
def f(v):
    return f"{float(v):.1f}"


def pt(x, y):
    return f"{f(x + OX)},{f(y + OY)}"


out = []


def tag(level, s):
    out.append("\t" * level + s)


