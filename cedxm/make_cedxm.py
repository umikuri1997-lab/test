def split_walls(segs):
    """T 字・十字の交点で壁を分割する(サンプルは交点ごとに分かれている)。"""
    pts = {a for s in segs for a in s}
    out = []
    for (x1, y1), (x2, y2) in segs:
        cuts = [(x1, y1), (x2, y2)]
        for (x, y) in pts:
            if x1 == x2 == x and min(y1, y2) < y < max(y1, y2):
                cuts.append((x, y))
            elif y1 == y2 == y and min(x1, x2) < x < max(x1, x2):
                cuts.append((x, y))
        cuts.sort(key=lambda c: (c[0] - x1) ** 2 + (c[1] - y1) ** 2)
        out += list(zip(cuts, cuts[1:]))
    return out


